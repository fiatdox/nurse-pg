/**
 * เลข HN ของโรงพยาบาล
 *
 * ใน HIS เก็บเป็นตัวเลขเก้าหลักเติมศูนย์หน้าเสมอ (เช่น 000635972)
 * ค้นด้วย 635972 จะไม่เจอ เพราะเทียบเป็นข้อความตรงตัว ไม่ใช่เทียบเป็นจำนวน
 *
 * คนพิมพ์มักพิมพ์เฉพาะตัวเลขท้ายที่จำได้ และเครื่องอ่านบางตัวก็ตัดศูนย์หน้าทิ้ง
 * จึงต้องเติมให้ครบก่อนเสมอ ไม่ใช่ปล่อยให้ค้นไม่เจอแล้วบอกว่าไม่มีผู้ป่วยคนนี้
 */

export const HN_LENGTH = 9;

/**
 * เติมศูนย์หน้าให้ครบเก้าหลัก
 * ของที่ยาวเกินเก้าหลักคืนไปตามเดิม ไม่ตัดให้ เพราะไม่รู้ว่าต้องตัดหัวหรือท้าย
 * และการเดาผิดแปลว่าไปเจอผู้ป่วยคนอื่น
 */
export const padHn = (raw: string): string => {
    const digits = String(raw ?? '').trim();
    if (!/^\d+$/.test(digits)) return digits;
    return digits.length < HN_LENGTH ? digits.padStart(HN_LENGTH, '0') : digits;
};
