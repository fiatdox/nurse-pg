-- ผูกสัญญาราคาอาหารเข้ากับบริษัทผู้รับจ้าง
-- ฐานข้อมูล: nurse

/*
  ของเดิมสัญญาผูกกับประเภทอาหารอย่างเดียว ระบบจึงตอบได้แค่
  "ประเภทนี้ราคาเท่าไหร่ ณ วันนี้" แต่ตอบไม่ได้ว่า "สัญญาฉบับนี้เป็นของใคร"

  ผลคือบริษัทที่ผูกกับประเภทหนึ่ง จะเห็นสัญญาทุกฉบับของประเภทนั้น
  รวมถึงฉบับของรอบประกวดราคาถัดไปที่อาจเป็นของเจ้าอื่น
  และถ้าเลือกช่วงคร่อมสองสัญญา ระบบจะคิดเงินทั้งสองช่วงให้บริษัทเดียว

  พอเติม vendor_id หนึ่งแถวจะตอบครบว่า ใคร · ประเภทไหน · ช่วงไหน · ราคาเท่าไหร่

  ยังเก็บ vendor_food_types ไว้ เพราะตอบคนละคำถาม
  ตารางนั้นคือ "วันนี้ต้องทำอาหารประเภทไหน" (ใบงานครัว)
  ส่วนสัญญาคือ "ได้เงินจากอะไร ช่วงไหน" ถ้ายุบเป็นตารางเดียว
  ช่วงที่สัญญายังไม่ถูกบันทึกเข้าระบบ บริษัทจะเปิดใบงานครัวไม่ได้เลย
  ทั้งที่ยังต้องทำอาหารส่งอยู่
*/

BEGIN;

ALTER TABLE food_type_prices
    ADD COLUMN IF NOT EXISTS vendor_id integer REFERENCES vendors (vendor_id);

/*
  สัญญาที่มีอยู่ก่อนหน้านี้ทั้งหมดเป็นของบริษัทที่บันทึกไว้รายแรก
  เติมย้อนหลังให้ทีเดียว ไม่ปล่อยเป็น NULL ค้างไว้
  เพราะแถวที่ไม่มีเจ้าของจะไม่ปรากฏในหน้าของบริษัทไหนเลย แล้วยอดจะหายเงียบ

  เขียนแบบเลือกบริษัทที่มี vendor_id น้อยที่สุด ไม่ฝังเลข 4 ไว้ในไฟล์
  เพื่อให้ไฟล์นี้รันบนเครื่องอื่นที่เลขไม่ตรงกันแล้วยังได้ผลเดียวกัน
*/
UPDATE food_type_prices
SET vendor_id = (SELECT MIN(vendor_id) FROM vendors)
WHERE vendor_id IS NULL
  AND EXISTS (SELECT 1 FROM vendors);

CREATE INDEX IF NOT EXISTS ix_food_type_prices_vendor
    ON food_type_prices (vendor_id, food_type_id, effective_from DESC);

COMMENT ON COLUMN food_type_prices.vendor_id IS
    'บริษัทคู่สัญญาของราคาฉบับนี้ NULL = ยังไม่ระบุ ซึ่งจะไม่ปรากฏในหน้าของบริษัทใดเลย';

COMMIT;
