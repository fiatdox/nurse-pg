-- การอนุมัติรายการอาหารก่อนส่งให้บริษัทผู้รับจ้าง
-- ฐานข้อมูล: nurse

/*
  ลำดับการทำงานของรายการอาหารหนึ่งรายการ

    หอผู้ป่วยสั่ง  →  งานโภชนาการอนุมัติ  →  บริษัททำอาหารและส่ง  →  งานโภชนาการรับมอบ
                      (approved_at)                                  (recieve_order_status)

  บริษัทเห็นเฉพาะรายการที่อนุมัติแล้ว ต่างจากงานโภชนาการที่เห็นทุกรายการตั้งแต่หอสั่งเข้ามา
  เพราะรายการดิบยังแก้ไขได้ตลอดจนถึงเวลาปิดยอด ถ้าให้บริษัทเห็นทันที
  บริษัทจะตั้งหม้อตามยอดที่ยังไม่นิ่ง แล้วของที่ทำเกินจะไม่มีใครรับผิดชอบ

  เก็บเป็นคอลัมน์รายแถว ไม่ใช่ตารางอนุมัติรายมื้อ

  ถ้าเก็บเป็น "มื้อนี้อนุมัติแล้ว" รายการที่หอเพิ่งสั่งเพิ่มหลังอนุมัติจะกลายเป็น
  อนุมัติแล้วไปด้วยโดยไม่มีใครเห็น แล้วใบที่บริษัทพิมพ์ไปก่อนหน้าจะไม่ตรงกับยอดในระบบ
  เก็บรายแถวทำให้รายการที่มาทีหลังยังไม่อนุมัติ และงานโภชนาการเห็นว่ามีของใหม่ให้ตรวจซ้ำ
*/

BEGIN;

ALTER TABLE food_orders
    ADD COLUMN IF NOT EXISTS approved_at      timestamp,
    ADD COLUMN IF NOT EXISTS approved_by      integer,
    ADD COLUMN IF NOT EXISTS approved_by_name varchar(150);

/*
  ดัชนีสำหรับคิวรีของบริษัท ซึ่งกรองด้วย วันที่ + มื้อ + อนุมัติแล้ว เสมอ
  ใส่เงื่อนไขไว้ในดัชนีเลย เพราะรายการที่ยังไม่อนุมัติไม่เคยถูกค้นจากฝั่งนั้น
*/
CREATE INDEX IF NOT EXISTS ix_food_orders_approved
    ON food_orders (order_date, meal, ward)
    WHERE approved_at IS NOT NULL AND cancelled_at IS NULL;

COMMENT ON COLUMN food_orders.approved_at IS
    'เวลาที่งานโภชนาการอนุมัติให้ส่งบริษัท NULL = ยังไม่อนุมัติ บริษัทจะยังมองไม่เห็น';
COMMENT ON COLUMN food_orders.approved_by_name IS
    'ชื่อผู้อนุมัติ เก็บไว้กับแถวเพราะต้องอ้างอิงย้อนหลังได้แม้บัญชีผู้ใช้จะถูกปิดไปแล้ว';

COMMIT;
