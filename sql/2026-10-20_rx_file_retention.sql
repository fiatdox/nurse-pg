-- ลบไฟล์ใบสั่งยาที่เก็บครบกำหนด
-- ฐานข้อมูล: nurse

/*
  ลบเฉพาะ "ไฟล์ภาพ" บนดิสก์ ไม่ลบแถวในฐานข้อมูล
  แถวของใบสั่งยา ชื่อผู้ป่วย สถานะ และประวัติว่าใครทำอะไรเมื่อไร ยังอยู่ครบ
  เพราะเป็นหลักฐานตรวจสอบย้อนหลังที่ต้องเก็บนานกว่าภาพ และกินที่น้อยมาก

  purged_at บอกว่าไฟล์นี้ถูกลบไปแล้วเมื่อไร หน้าจอจะได้บอกผู้ใช้ตรง ๆ ว่า "ลบตามกำหนดแล้ว"
  ไม่ใช่ขึ้นว่า "เปิดไฟล์ไม่สำเร็จ" แล้วให้คนไปแจ้งว่าระบบเสีย

  จำนวนวันเก็บอยู่ใน system_settings key = 'rx_file_retention' ค่าเริ่มต้น 120 วัน
  (ไม่ต้องใส่แถวไว้ล่วงหน้า โค้ดใช้ค่าเริ่มต้นเองเมื่อยังไม่มีใครตั้ง)
*/

BEGIN;

ALTER TABLE rx_order_files ADD COLUMN IF NOT EXISTS purged_at timestamp;

/* ตัวลบหาไฟล์ที่ยังไม่ถูกลบและเก่ากว่ากำหนด ทำ index เฉพาะแถวที่ยังไม่ถูกลบ ตารางโตไปก็ยังเร็ว */
CREATE INDEX IF NOT EXISTS ix_rx_order_files_retention
    ON rx_order_files (uploaded_at) WHERE purged_at IS NULL;

COMMENT ON COLUMN rx_order_files.purged_at IS
    'เวลาที่ไฟล์ภาพถูกลบออกจากดิสก์ตามระยะเวลาจัดเก็บ ว่าง = ไฟล์ยังอยู่';

COMMIT;
