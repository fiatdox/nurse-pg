-- NICU ใช้รหัสแผนกเดียวกับกุมารเวชกรรมของ HIS
-- ฐานข้อมูล: nurse

/*
  spclty.code คือรหัสแผนกฝั่ง HIS (ipt.spclty) ส่วน spclty คือรหัสของระบบพยาบาลเอง
  สองฝั่งคนละชุดกัน และเลขที่บังเอิญตรงกันก็คนละแผนก
  เช่น 10 ที่นี่คืออายุรกรรม แต่ 10 ของ HIS คือแพทย์ทางเลือก
  คอลัมน์ code จึงเป็นสะพานเดียวที่ใช้เทียบสองฝั่งได้

  NICU เคยตั้งเป็น '99' ซึ่งไม่มีอยู่จริงใน HIS
  ผลคือแปลงกลับไปฝั่ง HIS ไม่ได้ และผู้ป่วย NICU ที่ HIS ลงไว้เป็นกุมารเวชกรรม
  ก็เทียบมาหาแถวนี้ไม่ได้เช่นกัน

  ในทางคลินิก NICU เป็นหอผู้ป่วย ไม่ใช่แผนกการรักษา
  ผู้ป่วยที่นอน NICU อยู่ใต้กุมารเวชกรรมซึ่ง HIS ใช้รหัส 01

  หลังแก้จะมีสองแถวที่ code = '01' (กุมารเวชกรรม กับ NICU) ซึ่งตั้งใจให้เป็นแบบนั้น
  ทิศทางที่มีได้หลายค่าคือ ระบบพยาบาล -> HIS (หลายแถวชี้ไปรหัสเดียว)
  ส่วนทิศทางขากลับ HIS -> ระบบพยาบาล ต้องมีกติกาตัดสิน ซึ่งอยู่ที่ toLocalSpclty
  ในหน้าลงทะเบียน คือเทียบชื่อจาก HIS ก่อน ไม่ตรงค่อยเอาแถวที่เลขน้อยสุด
  ผลคือ HIS ส่ง 01 กุมารเวชกรรม มา จะได้กุมารเวชกรรม ไม่ใช่ NICU
*/

BEGIN;

UPDATE spclty
SET code = '01'
WHERE name = 'NICU'
  AND code = '99';

COMMENT ON COLUMN spclty.code IS
    'รหัสแผนกฝั่ง HIS (ipt.spclty) หลายแถวชี้รหัสเดียวกันได้ เช่น NICU กับกุมารเวชกรรมใช้ 01 ทั้งคู่';

COMMIT;
