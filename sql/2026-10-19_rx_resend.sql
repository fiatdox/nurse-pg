-- ส่งใบสั่งยาซ้ำ หลังห้องยาส่งกลับให้แก้
-- ฐานข้อมูล: nurse

/*
  หอแก้แล้วส่งใหม่เป็น "ใบใหม่" เสมอ ไม่ใช่แก้ใบเดิม
  เพราะใบเดิมคือหลักฐานว่าเคยส่งอะไรไปและถูกตีกลับเพราะอะไร ถ้าทับของเดิมหลักฐานนั้นหาย

  แต่ถ้าไม่ผูกสองใบไว้ด้วยกัน ห้องยาจะเห็นใบของผู้ป่วยคนเดิมสองใบในวันเดียว
  แล้วแยกไม่ออกว่าเป็นการแก้ไข หรือเป็นออร์เดอร์ที่สองจริง ๆ ซึ่งแปลว่าจ่ายยาซ้ำได้
  คอลัมน์นี้จึงมีไว้ตอบว่า "ใบนี้คือฉบับแก้ของใบไหน"

  ON DELETE SET NULL เพราะถ้าวันหนึ่งใบเก่าถูกลบตามนโยบายเก็บข้อมูล
  ใบที่ส่งซ้ำต้องไม่หายตามไปด้วย แค่ชี้กลับไปไม่ได้เท่านั้น
*/

BEGIN;

ALTER TABLE rx_orders ADD COLUMN IF NOT EXISTS resend_of bigint
    REFERENCES rx_orders (rx_order_id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS ix_rx_orders_resend_of ON rx_orders (resend_of);

COMMENT ON COLUMN rx_orders.resend_of IS 'ใบนี้เป็นฉบับแก้ของใบเลขนี้ (ใบเดิมถูกห้องยาส่งกลับ)';

COMMIT;
